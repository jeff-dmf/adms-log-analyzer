"""Build dist/dmslog.pyz, the zipapp shared by Windows and Linux.

Run on any OS:  python packaging/build_pyz.py
The build is deterministic for a given source tree and commit: files are added in sorted
order with fixed timestamps and permissions, and no .pyc files are included.
The commit hash is written to dmslog/_build_info.py inside the archive only (the repo
checkout is never modified). Set DMSLOG_COMMIT to override the detected hash.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_PACKAGE = ROOT / "src" / "dmslog"
DIST = ROOT / "dist"
TARGET = DIST / "dmslog.pyz"

FIXED_MTIME = 1_700_000_000  # 2023-11-14 UTC, epoch seconds: used for tar entries (zone independent)
ZIP_EPOCH = (2023, 11, 14, 0, 0, 0)  # fixed ZIP entry time: independent of mtime and of the local time zone
INTERPRETER = "/usr/bin/env python3"

MAIN_PY = """\
import sys

from dmslog.cli import main

sys.exit(main())
"""


def detect_commit() -> str:
    """Return the short commit hash of HEAD, "-dirty" appended for uncommitted changes."""
    override = os.environ.get("DMSLOG_COMMIT")
    if override:
        return override
    try:

        def git(*args: str) -> str:
            return subprocess.run(
                ["git", *args], cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8"
            ).stdout.strip()

        commit = git("rev-parse", "--short=12", "HEAD")
        if git("status", "--porcelain", "--", "src"):
            commit += "-dirty"
        return commit
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


# The knowledge pack is derived from product documentation: it is never embedded in the zipapp, even
# when a developer has a local copy under src/ (ARQUITETURA D10). It is installed next to it instead.
EXCLUDED_DIRS = (("knowledge", "pack"),)
_IGNORED = shutil.ignore_patterns("__pycache__", "*.pyc", "_build_info.py")


def _ignore(directory: str, names: list[str]) -> set[str]:
    ignored = set(_IGNORED(directory, names))
    parent = Path(directory).name
    ignored.update(name for name in names if (parent, name) in EXCLUDED_DIRS)
    return ignored


def stage(staging: Path, commit: str) -> None:
    """Copy the package into a staging tree, add __main__.py and _build_info.py."""
    shutil.copytree(SRC_PACKAGE, staging / "dmslog", ignore=_ignore)
    (staging / "dmslog" / "_build_info.py").write_text(
        f'"""Generated by packaging/build_pyz.py. Do not edit."""\n\nCOMMIT = "{commit}"\n',
        encoding="utf-8",
        newline="\n",
    )
    (staging / "__main__.py").write_text(MAIN_PY, encoding="utf-8", newline="\n")


def write_archive(staging: Path, target: Path) -> None:
    """Write a zipapp whose bytes depend only on the staged content.

    zipapp.create_archive stores each file's mtime converted to LOCAL time, so the same sources
    give different bytes under different time zones. Entries are written here with fixed metadata.
    """
    with target.open("wb") as handle:
        handle.write(f"#!{INTERPRETER}\n".encode())
        with zipfile.ZipFile(handle, "w", zipfile.ZIP_DEFLATED) as archive:
            for path in sorted(p for p in staging.rglob("*") if p.is_file()):
                info = zipfile.ZipInfo(path.relative_to(staging).as_posix(), date_time=ZIP_EPOCH)
                info.compress_type = zipfile.ZIP_DEFLATED
                info.create_system = 3  # Unix, whatever the build host is
                info.external_attr = 0o644 << 16
                archive.writestr(info, path.read_bytes())
    target.chmod(0o755)


def build() -> Path:
    commit = detect_commit()
    DIST.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="dmslog-pyz-") as tmp:
        staging = Path(tmp)
        stage(staging, commit)
        if TARGET.exists():
            TARGET.unlink()
        write_archive(staging, TARGET)
    print(f"built {TARGET} ({TARGET.stat().st_size / 1e3:.0f} kB, commit {commit})")
    return TARGET


if __name__ == "__main__":
    build()
