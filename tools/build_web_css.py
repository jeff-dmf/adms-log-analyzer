#!/usr/bin/env python3
"""Concatenates the stylesheets of the viewer into ``src/dmslog/web/css/bundle.css``.

The sheets stay separate files (the source of truth, one per feature); the page links only the bundle, so opening it
costs one request instead of about forty. The order is the cascade order listed in ``css/bundle.order.txt``.
No build step at run time: the bundle is committed, and ``test_web_assets`` fails when it is stale.

    python tools/build_web_css.py            # rewrite bundle.css
    python tools/build_web_css.py --check    # exit 1 when bundle.css is not up to date
"""

from __future__ import annotations

import sys
from pathlib import Path

WEB = Path(__file__).resolve().parents[1] / "src" / "dmslog" / "web"
CSS = WEB / "css"
ORDER = CSS / "bundle.order.txt"
BUNDLE = CSS / "bundle.css"


def sheet_names(order_path: Path = ORDER) -> list[str]:
    names = []
    for line in order_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            names.append(line)
    return names


def bundle_text(css_dir: Path = CSS, order_path: Path = ORDER) -> str:
    """The bundle: a header, then every sheet under a comment naming it, LF line ends, one blank line apart."""
    parts = ["/* Generated by tools/build_web_css.py from css/bundle.order.txt. Do not edit: edit the sheets. */\n"]
    for name in sheet_names(order_path):
        text = (css_dir / name).read_text(encoding="utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")
        parts.append(f"\n/* ---- {name} ---- */\n{text.rstrip()}\n")
    return "".join(parts)


def main(argv: list[str]) -> int:
    text = bundle_text()
    if "--check" in argv:
        current = BUNDLE.read_text(encoding="utf-8") if BUNDLE.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("css/bundle.css is stale: run python tools/build_web_css.py", file=sys.stderr)
            return 1
        return 0
    BUNDLE.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {BUNDLE} ({len(text.encode('utf-8'))} bytes, {len(sheet_names())} sheets)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
